  function detectBrowserLocale(lang) {
    return /^zh\b/i.test(String(lang || "")) ? "zh" : "en";
  }

  function resolveLocale(preference, browserLang) {
    if (preference === "en" || preference === "zh") {
      return preference;
    }
    return detectBrowserLocale(browserLang);
  }

  function t(locale, key, vars) {
    const dict = MESSAGES[locale] || MESSAGES.en;
    const brand = dict.brandName || MESSAGES.en.brandName;
    let text = dict[key] ?? MESSAGES.en[key] ?? key;
    const merged = { brand, ...(vars || {}) };
    for (const [name, value] of Object.entries(merged)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
    return text;
  }

  root.HackerBaI18n = {
    MESSAGES,
    detectBrowserLocale,
    resolveLocale,
    t,
  };
